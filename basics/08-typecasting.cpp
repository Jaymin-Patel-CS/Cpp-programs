#include<iostream>

using namespace std;

int main()
{
    int a= 22;
    float b = 2.5;
    cout<<"The value of a before typecasting is "<<a<<endl;
    cout<<"The value of a after typecasting is "<<float(a)<<endl;
    cout<<"The value of b before typecasting is "<<b<<endl;
    cout<<"The value of b after typecasting is "<<int(b)<<endl;
    return 0;
}
